"""Markdown results report for a campaign (the evidence, readable without the dashboard)."""

from __future__ import annotations

import json
from pathlib import Path

from greenbench import __version__
from greenbench.analysis.analyze import analyze_campaign


def _f(v, digits=2):
    return "–" if v is None else f"{v:,.{digits}f}"


def _ci(m: dict, digits=2) -> str:
    return f"{_f(m['median'], digits)} [{_f(m['ci_low'], digits)}, {_f(m['ci_high'], digits)}]"


def _pct(v):
    return "–" if v is None else f"{v:+.1f}%"


def write_report(cdir: Path, out: Path | None = None) -> Path:
    cdir = Path(cdir)
    campaign = json.loads((cdir / "campaign.json").read_text(encoding="utf-8"))
    a = analyze_campaign(cdir)
    cfg, env = campaign["config"], campaign["environment"]
    pm = a["primary_metric"]
    metric_label = a["metrics"][pm]["label"].lower()
    meter = campaign.get("primary_meter") or {}
    configs = {c["key"]: c for c in a["configs"]}
    lines = [
        f"# Campaign `{a['campaign_id']}`: results",
        "",
        f"Generated by GreenBench {__version__}. Preset **{cfg['preset']}**: {cfg['scale']} datasets, "
        f"{cfg['repetitions']} measured repetitions per configuration after {cfg['warmups']} discarded warm-ups, "
        f"randomised order, one fresh process per run. Primary metric: **{metric_label}** "
        f"({a['metrics'][pm]['description']})",
        "",
        "## Recommendations",
        "",
    ]
    for rec in a["recommendations"]:
        tag = "" if rec["significant"] else " _(not significant)_"
        lines.append(f"- {rec['text']}{tag}")
    lines += ["", "## Machine and measurement", "",
              "| Item | Value |", "|---|---|",
              f"| CPU | {env['cpu']['name']} ({env['cpu']['physical_cores']} cores / {env['cpu']['logical_cpus']} threads) |",
              f"| Memory | {env['memory_gb']} GB |",
              f"| OS | {env['os']['system']} {env['os']['release']} ({env['os']['version']}) |",
              f"| Python / NumPy / Arrow | {env['python']['version']} / {env['libraries']['numpy']} / "
              f"{env['libraries']['pyarrow']} |",
              f"| Power | plan {env['power']['plan'] or 'n/a'}, AC plugged: {env['power']['ac_plugged']} |",
              f"| Virtualisation | {'yes' if env['virtualization']['virtualized'] else 'none detected'} |",
              f"| Energy meter | {meter.get('interface', 'software model only')}"
              f"{' (' + meter.get('provider', '') + ')' if meter.get('provider') else ''}, "
              f"domains: {', '.join(meter.get('domains', [])) or 'n/a'} |",
              f"| Idle package power | {_f(a['idle_w'])} W (drift {_f(a['idle_drift_w'])} W over the campaign) |",
              f"| Background load at idle | {_f(a['idle_background_cores'])} cores |",
              f"| Software model | TDP {env['cpu']['tdp_w']} W ({env['cpu']['tdp_source']}) |",
              "", "## Measurement quality", ""]
    q = a["quality"]
    lines.append(f"- {q['valid']} of {q['runs']} measured runs valid; {q['invalid']} failed result validation, "
                 f"{q['errors']} errors, {q['noisy']} flagged for background load.")
    if q.get("median_cv") is not None:
        lines.append(f"- Median coefficient of variation of the {metric_label} across configurations: "
                     f"{q['median_cv'] * 100:.1f}%.")
    mc = a.get("meter_check")
    if mc:
        lines.append(f"- Hardware vs software model ({mc['n']} runs): Spearman ρ = {mc['spearman_model_vs_dynamic']:.2f}, "
                     f"Pearson r = {mc['pearson_model_vs_dynamic']:.2f}; the model estimates "
                     f"{_f(mc['median_ratio_model_over_dynamic'])}× the measured dynamic energy (median).")
        v = mc.get("verdicts")
        if v:
            lines.append(f"- Of the {v['hardware_significant_pairs']} configuration pairs the hardware counter separates "
                         f"(p < 0.05), the model agrees on {v['model_agrees']} and significantly reverses "
                         f"{v['model_reverses']}:")
            lines += [f"  - {r['a']} vs {r['b']}: hardware ×{r['hardware_ratio']:.2f}, model ×{r['model_ratio']:.2f}"
                      for r in v["reversals"]]
    if campaign.get("corrections"):
        lines += ["", "**Corrections to recorded metadata:**"] + [f"- {c}" for c in campaign["corrections"]]
    for s in a["studies"]:
        lines += ["", f"## {s['title']}", "", f"_{s['question']}_", ""]
        for g in s["groups"]:
            if g["group"]:
                lines += [f"**{', '.join(f'{k} = {v:,}' for k, v in g['group'].items())}**", ""]
            lines += ["| Configuration | " + a["metrics"][pm]["label"] + " (J), median [95% CI] | Δ energy | "
                      "Duration (s) | Δ duration | p (Holm) | Cliff's δ |",
                      "|---|---|---|---|---|---|---|"]
            for r in g["rows"]:
                c = configs[r["key"]]
                if r.get("skipped"):
                    lines.append(f"| {r['label']} | skipped: {r['skipped']} | | | | | |")
                    continue
                if pm not in c["metrics"]:
                    lines.append(f"| {r['label']} | no valid run | | | | | |")
                    continue
                name = f"**{r['label']}** (baseline)" if r["is_baseline"] else r["label"]
                if r.get("pareto"):
                    name += " ◆"
                acc = c.get("accuracy")
                if acc:
                    worst = max(acc.items(), key=lambda kv: kv[1]["mape"])
                    name += f" ({worst[1]['mape'] * 100:.1f}% error on {worst[0].replace('_', ' ')})"
                p = r.get("p_adj")
                p_txt = "–" if p is None else f"{p:.3g}"
                d = r.get("cliffs_delta")
                d_txt = "–" if d is None else f"{d:+.2f} ({r['magnitude']})"
                lines.append(
                    f"| {name} | {_ci(c['metrics'][pm], 3)} | {_pct(r.get('energy_change_pct'))} | "
                    f"{_f(c['metrics']['duration_s']['median'], 3)} | {_pct(r.get('duration_change_pct'))} | "
                    f"{p_txt} | {d_txt} |")
            lines.append("")
        lines += [f"- {i}" for i in s["insights"]]
    lines += ["", "◆ = on the energy/duration Pareto front of its group.", "",
              "## Limitations", "",
              "- One machine, one operating system: results describe this laptop, not hardware in general.",
              "- The package domain covers the CPU package only (cores, caches, memory controller, integrated GPU): "
              "DRAM, storage and the rest of the platform are not measured.",
              "- On AMD processors RAPL energy is produced by an on-chip power model rather than a physical sensor "
              "(Schöne et al., 2021); differences between variants are trustworthy, absolute joules less so.",
              "- Dynamic energy subtracts a single idle baseline; background activity that differs from idle is "
              "tracked per run and flagged.",
              "- Windows CPU-time counters advance in 15.6 ms ticks, so the software model is coarse for very short runs."]
    out = out or cdir / "report.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out
